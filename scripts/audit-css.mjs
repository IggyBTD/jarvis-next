// Finds every margin, padding, gap, width, height, border-radius and line-height that is not on the spacing scale.
//   node scripts/audit-css.mjs                       print the findings
//   node scripts/audit-css.mjs --write docs/x.md     also write them to a file
//   node scripts/audit-css.mjs --fail                exit 1 when anything is off the scale (npm run lint:spacing)
// Scale: px values are 0 or multiples of 4 (1px is allowed for width and height: dividers and hairlines).
// Relative units (%, em, ch, vh, fr ...), var(--tokens), auto and friends are always fine. A line that
// carries `/* optical: reason */` is skipped, which is how a 2px frame or a 1.5px stroke is declared.
// Scans src/**/*.css, the CSS in index.html (style tags and style="" attributes) and nothing else.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const args = process.argv.slice(2);
const fail = args.includes('--fail');
const outFile = args.includes('--write') ? args[args.indexOf('--write') + 1] : null;

const PROPS = /^(margin(-(top|right|bottom|left|inline|block)(-(start|end))?)?|padding(-(top|right|bottom|left|inline|block)(-(start|end))?)?|gap|row-gap|column-gap|width|height|min-width|min-height|max-width|max-height|border-radius|line-height)$/;
const SIZE = /^(width|height|min-width|min-height|max-width|max-height)$/;

function walk(dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) { if (!['sets', 'dev'].includes(f)) walk(p, out); } else if (p.endsWith('.css')) out.push(p);
  }
  return out;
}

function bad(prop, value) {
  const v = value.replace(/var\([^)]*\)/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ');
  const found = [];
  for (const m of v.matchAll(/(-?\d*\.?\d+)(px|em|rem|%|ch|vh|vw|fr|deg|s|ms)?(?![\w-])/g)) {
    const [, num, unit] = m;
    const n = Number(num);
    if (prop === 'line-height' && !unit && n !== 0) { found.push(`${num} (unitless)`); continue; }
    if (unit !== 'px') continue;
    if (n === 0 || n % 4 === 0) continue;
    if (n === 1 && SIZE.test(prop)) continue;
    found.push(`${num}px`);
  }
  return found;
}

function scan(text, file, base = 0) {
  const hits = [];
  text.split('\n').forEach((line, i) => {
    if (/\/\*\s*optical/.test(line)) return;
    for (const d of line.matchAll(/([a-z-]+)\s*:\s*([^;{}]+?)(?=;|\}|$)/g)) {
      const prop = d[1];
      if (!PROPS.test(prop)) continue;
      const found = bad(prop, d[2]);
      if (found.length) hits.push({ file, line: base + i + 1, prop, value: d[2].trim(), found });
    }
  });
  return hits;
}

const root = process.cwd();
let hits = [];
for (const f of walk(join(root, 'src'))) hits.push(...scan(readFileSync(f, 'utf8'), relative(root, f)));
const html = readFileSync(join(root, 'index.html'), 'utf8');
for (const m of html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)) hits.push(...scan(m[1], 'index.html', html.slice(0, m.index).split('\n').length - 1));
html.split('\n').forEach((line, i) => { for (const m of line.matchAll(/style="([^"]*)"/g)) hits.push(...scan(m[1].replace(/;/g, ';\n'), 'index.html', i).map((h) => ({ ...h, line: i + 1 }))); });

const lines = hits.map((h) => `| ${h.file}:${h.line} | ${h.prop} | \`${h.value}\` | ${h.found.join(', ')} |`);
const report = `# Spacing audit\n\nGenerated by \`scripts/audit-css.mjs\`. ${hits.length ? `${hits.length} declarations are off the scale.` : 'Everything is on the scale.'}\n\n${hits.length ? `| Where | Property | Value | Off the scale |\n|---|---|---|---|\n${lines.join('\n')}\n` : ''}`;
if (outFile) writeFileSync(join(root, outFile), report);
if (hits.length) console.log(lines.slice(0, 40).join('\n') + (lines.length > 40 ? `\n... and ${lines.length - 40} more` : ''));
console.log(hits.length ? `${hits.length} off-scale declarations` : 'spacing scale: clean');
if (fail && hits.length) process.exit(1);
