// Run once, after picking an icon set in the dev switcher: npm run icons:finalise
//   reads icons/chosen.json ({ "set": "iconoir", "variant": "regular" })
//   keeps only that set (and its filled twin for active controls), inlines it into src/icons/icons.js,
//   removes the other generated sets and the dev switcher, and uninstalls the unused icon packages.
// Add --dry to print the plan and change nothing.
import { readFileSync, writeFileSync, readdirSync, rmSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { join } from 'node:path';

const dry = process.argv.includes('--dry');
const root = process.cwd();
const chosen = JSON.parse(readFileSync(join(root, 'icons/chosen.json'), 'utf8'));
const manifest = JSON.parse(readFileSync(join(root, 'src/icons/manifest.json'), 'utf8'));
const def = manifest.sets[chosen.set];
if (!def || !def.variants.includes(chosen.variant)) throw new Error(`icons/chosen.json names an unknown set: ${chosen.set}:${chosen.variant}`);

const keep = new Set([`${chosen.set}-${chosen.variant}.json`, ...(def.active ? [`${chosen.set}-${def.active}.json`] : [])]);
const dir = join(root, 'src/icons/sets');
const all = readdirSync(dir);
const drop = all.filter((f) => !keep.has(f));
const read = (f) => JSON.parse(readFileSync(join(dir, f), 'utf8'));
const base = read(`${chosen.set}-${chosen.variant}.json`);
const active = def.active ? read(`${chosen.set}-${def.active}.json`) : null;

const PACKAGES = { phosphor: '@phosphor-icons/core', tabler: '@tabler/icons', iconoir: 'iconoir', remix: 'remixicon', solar: '@iconify-json/solar', lucide: 'lucide-static' };
const unused = Object.entries(PACKAGES).filter(([k]) => k !== chosen.set).map(([, v]) => v);

console.log(`Keeping ${[...keep].join(', ')}`);
console.log(`Removing ${drop.length} generated set files, the dev switcher, and packages: ${unused.join(' ')}`);
if (dry) process.exit(0);

// 1. one module with the chosen icons and a small runtime (same exports as src/icons/index.js, minus the switcher)
writeFileSync(join(root, 'src/icons/icons.js'), `// Generated by scripts/finalise-icons.mjs from ${chosen.set}:${chosen.variant}. Do not edit by hand.
export const NAMES = ${JSON.stringify(manifest.names)};
export const BASE = ${JSON.stringify(base)};
export const ACTIVE = ${JSON.stringify(active)};
`);
writeFileSync(join(root, 'src/icons/index.js'), `// The one door to icons (final form: one set, no switcher). Same exports the app already imports.
import { NAMES, BASE, ACTIVE } from './icons.js';

const ALIAS = ${JSON.stringify({ clip: 'attach', down: 'chevron-down', left: 'chevron-left', right: 'chevron-right', attach_file: 'attach', mic_off: 'mic-off', language: 'globe', public_off: 'globe-off', wifi_off: 'wifi-off', 'win-maximize': 'win-max' })};
const SLASH = (w) => \`<path d="M\${w * 0.125} \${w * 0.125}L\${w * 0.875} \${w * 0.875}" fill="none" stroke="currentColor" stroke-width="\${w / 16}" stroke-linecap="round"/>\`;

export const semanticNames = () => NAMES;
export const getIconSet = () => '${chosen.set}:${chosen.variant}';
export const setIconSet = async () => {};
export const onIconSetChange = () => () => {};

export function renderFrom(src, name, { size } = {}) {
  const key = ALIAS[name] ?? name;
  const off = key.endsWith('-off') && !NAMES.includes(key);
  const inner = src?.icons[off ? key.slice(0, -4) : key];
  if (!inner) return '';
  const w = Number(src.viewBox.split(' ')[2]) || 24;
  const stroke = src.kind === 'stroke'
    ? ' fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round" stroke-width="1.5" style="stroke-width:var(--icon-stroke)"'
    : ' fill="currentColor"';
  const dim = size ? \` width="\${size}" height="\${size}"\` : '';
  return \`<svg class="ic ic-\${key}" viewBox="\${src.viewBox}"\${dim}\${stroke} aria-hidden="true" focusable="false">\${inner}\${off ? SLASH(w) : ''}</svg>\`;
}

function markup(name, active) {
  const src = active && ACTIVE?.icons[(ALIAS[name] ?? name).replace(/-off$/, '')] ? ACTIVE : BASE;
  return { svg: renderFrom(src, name) };
}

export function icon(name, { size } = {}) {
  const { svg } = markup(name, false);
  const style = size ? \` style="width:\${size}px;height:\${size}px"\` : '';
  return \`<span class="icon" data-icon="\${name}"\${size ? \` data-size="\${size}"\` : ''}\${style} aria-hidden="true">\${svg}</span>\`;
}

export function setIcon(el, name) { el.dataset.icon = name; hydrateOne(el); }

function hydrateOne(el) {
  el.classList.add('icon');
  const size = Number(el.dataset.size);
  if (size) { el.style.width = \`\${size}px\`; el.style.height = \`\${size}px\`; }
  const { svg } = markup(el.dataset.icon, !!el.closest('[data-active]'));
  if (el.innerHTML !== svg) el.innerHTML = svg;
}

export function hydrateIcons(root = document) {
  if (root.matches?.('[data-icon]')) hydrateOne(root);
  root.querySelectorAll('[data-icon]').forEach(hydrateOne);
}
`);

// 2. remove the other sets, the dev switcher and its import
for (const f of drop) rmSync(join(dir, f));
rmSync(join(root, 'src/dev'), { recursive: true, force: true });
const main = readFileSync(join(root, 'src/main.js'), 'utf8').replace(/\n\/\/ Dev only[\s\S]*?icon-switcher\.js'\);\n?/, '\n');
writeFileSync(join(root, 'src/main.js'), main);
rmSync(join(root, 'src/icons/manifest.json'), { force: true });

// 3. uninstall the packages that are no longer needed
execSync(`npm uninstall ${unused.join(' ')}`, { stdio: 'inherit' });
console.log('Done. The build script (npm run icons) no longer applies; delete scripts/build-icons.mjs and icons/icon-map.json when you are happy.');
