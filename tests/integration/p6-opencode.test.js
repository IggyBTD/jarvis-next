test('agent tasks: start, snapshot, summary, changed files, conversation note; queueing; abort; timeout; failure', async () => {
  const s = await makeAgentStack({ taskTimeoutMs: 1500 });
  try {
    const repo = path.join(s.wsDir, 'proj');
    fs.mkdirSync(repo);
    const git = (...a) => runProgram({ file: 'git', args: ['-C', repo, '-c', 'user.name=t', '-c', 'user.email=t@t', ...a] });
    const hasGit = (await git('init')).code === 0;
    if (hasGit) { fs.writeFileSync(path.join(repo, 'a.txt'), '1'); await git('add', '.'); await git('commit', '-m', 'init'); }
    const conv = s.conversations.ensure('conv1');

    const r1 = await s.router.invoke({ name: 'agent_task', args: { prompt: 'add a file', workspace: 'proj' } }, { target: 'pc', source: 'user', convId: conv.id });
    assert.equal(r1.ok, true);
    const id1 = r1.data.taskId;
    await waitFor(() => s.fake.rec.prompts.length === 1);
    assert.match(s.fake.rec.prompts[0].body.parts[0].text, /^Work in the subfolder "proj" of the workspace\.\n\nadd a file$/);
    assert.equal(s.tasks.get(id1).snapshot, hasGit);

    // a second task on the same computer waits
    const r2 = await s.router.invoke({ name: 'agent_task', args: { prompt: 'second' } }, { target: 'pc', source: 'user', convId: conv.id });
    assert.equal(s.tasks.get(r2.data.taskId).state, 'queued');
    assert.equal(s.fake.rec.prompts.length, 1);

    if (hasGit) fs.writeFileSync(path.join(repo, 'new.txt'), 'x');
    s.fake.finish(s.fake.rec.prompts[0].session, 'Added new.txt.');
    await waitFor(() => s.tasks.get(id1).state === 'done');
    const t1 = s.tasks.get(id1);
    assert.equal(t1.summary, 'Added new.txt.');
    if (hasGit) assert.deepEqual((t1.files ?? [{ path: JSON.stringify(t1) }]).map((f) => f.path), ['new.txt']);
    const note = s.conversations.get('conv1').messages.find((m) => m.role === 'system');
    assert.match(note.content, /Agent task .* done\.[\s\S]*<untrusted source="agent summary">[\s\S]*Added new\.txt\./);
    assert.ok(s.events.some((e) => e.type === 'chat.note'));

    // the queued one starts when the first ends, then is aborted
    await waitFor(() => s.fake.rec.prompts.length === 2);
    assert.equal(await s.tasks.abort(r2.data.taskId), true);
    assert.equal(s.tasks.get(r2.data.taskId).state, 'aborted');
    assert.equal(s.fake.rec.aborts.length, 1);

    // failure from OpenCode
    const r3 = await s.router.invoke({ name: 'agent_task', args: { prompt: 'will fail' } }, { target: 'pc', source: 'user' });
    await waitFor(() => s.fake.rec.prompts.length === 3);
    s.fake.fail(s.fake.rec.prompts[2].session, 'model exploded');
    await waitFor(() => s.tasks.get(r3.data.taskId).state === 'failed');
    assert.match(s.tasks.get(r3.data.taskId).error, /model exploded/);

    // timeout
    const r4 = await s.router.invoke({ name: 'agent_task', args: { prompt: 'slow' } }, { target: 'pc', source: 'user' });
    await waitFor(() => s.tasks.get(r4.data.taskId).state === 'timeout', { timeout: 6000 });
    assert.match(s.tasks.get(r4.data.taskId).error, /stopped after/);
    assert.ok(s.fake.rec.aborts.length >= 2);

    // arguments are checked
    for (const workspace of ['../x', '/abs', 'c:\\x', 'a/../b', 'a\\b']) assert.equal((await s.router.invoke({ name: 'agent_task', args: { prompt: 'x', workspace } }, { target: 'pc', source: 'user' })).ok, false, workspace);
    assert.equal((await s.router.invoke({ name: 'agent_task', args: { prompt: '' } }, { target: 'pc', source: 'user' })).ok, false);
  } finally { await s.close(); }
});

test('the agent never proxies the shell route and the repo never builds a path to it', async () => {
  const s = await makeAgentStack();
  try {
    const auth = { authorization: `Bearer ${s.tokens.machines.pc[0]}` };
    const base = `http://127.0.0.1:${s.cfg.machines.machines.pc.agentPort}`;
    for (const p of ['/opencode/session/ses_1/shell', '/opencode/session/ses_1/shell/', '/opencode/session/ses_1%2Fshell']) assert.ok([403, 404].includes((await request(`${base}${p}`, { method: 'POST', headers: auth, body: '{}' })).status), p);
    await assert.rejects(s.router.capabilities('pc').opencode('POST', '/session/ses_1/shell', {}), /shell route|allowlist/);
    assert.equal(s.fake.rec.shellCalls.length, 0);
  } finally { await s.close(); }
  const allowed = new Set(['server/core/agent-client.js', 'agent/index.js', 'shared/opencode-routes.js']);
  for (const dir of ['server', 'agent', 'shared']) {
    const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
    for (const f of walk(dir).filter((x) => x.endsWith('.js'))) {
      const rel = f.split(path.sep).join('/');
      if (!allowed.has(rel)) assert.ok(!/\/shell\b/.test(fs.readFileSync(f, 'utf8')), `${rel} mentions the shell route`);
    }
  }
});

