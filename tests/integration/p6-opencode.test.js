test('manager: restarts with backoff after a crash, tells listeners, and stop() stays stopped', async () => {
  const dir = tmpDir('mgr3');
  const { manager } = realManager(dir, { port: await freePort(), extraEnv: { FAKE_OPENCODE_CRASH_MS: '700' } });
  const seen = [];
  manager.events.on('event', (e) => seen.push(e.type));
  try {
    assert.equal(await manager.start(), true);
    await waitFor(() => seen.includes('opencode.exited') && seen.includes('opencode.restarted'), { timeout: 15000 });
    assert.ok(manager.status().restarts >= 1);
    await waitFor(() => manager.status().running, { timeout: 10000 });
    await manager.stop();
    const restarts = manager.status().restarts;
    await new Promise((r) => setTimeout(r, 400));
    assert.equal(manager.status().restarts, restarts);
    assert.equal(manager.status().running, false);
  } finally { await manager.stop(); rmDir(dir); }
});

