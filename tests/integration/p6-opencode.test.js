test('manager (real child process): version pin, password auth, cleaned env, config, workspace, AGENTS.md', async () => {
  const dir = tmpDir('mgr');
  process.env.JARVIS_TEST_SECRET_TOKEN = 'must-not-leak';
  const port = await freePort();
  const { manager, log } = realManager(dir, { port, facts: { hostname: 'h', os: 'win32', os_version: 'Windows 11', user: 'u', shell: 'PowerShell', path_sep: '\\', package_manager: 'winget', modifier_key: 'Ctrl', workspace_dir: path.join(dir, 'ws') } });
  try {
    assert.equal(await manager.start(), true);
    const st = manager.status();
    assert.deepEqual([st.running, st.version, st.installed, st.routes.permissionReply], [true, '1.19.1', true, 'new']);
    const [started] = lines(log);
    assert.deepEqual(started.args, [BIN, 'serve', '--hostname', '127.0.0.1', '--port', String(port)].slice(1));
    assert.equal(fs.realpathSync(started.cwd), fs.realpathSync(path.join(dir, 'ws')));
    assert.match(started.password, /^[0-9a-f]{48}$/);
    assert.equal(started.env.JARVIS_TEST_SECRET_TOKEN, undefined);
    assert.equal(started.env.OPENCODE_DISABLE_PROJECT_CONFIG, '1');
    const cfg = JSON.parse(started.config);
    assert.equal(cfg.provider.jarvis.options.baseURL, 'http://pc:7410/v1');
    assert.equal(cfg.provider.jarvis.options.apiKey, 'x'.repeat(64));
    assert.match(fs.readFileSync(path.join(dir, 'ws', 'AGENTS.md'), 'utf8'), /Windows 11/);

    // the server itself demands the password: direct calls without it fail
    assert.equal((await get(`http://127.0.0.1:${port}/doc`)).status, 401);
    assert.equal((await get(`http://127.0.0.1:${port}/doc`, { authorization: `Basic ${Buffer.from(`opencode:${started.password}`).toString('base64')}` })).status, 200);
    await manager.stop();
    assert.equal(manager.status().running, false);

    // a user-owned AGENTS.md is never overwritten
    fs.writeFileSync(path.join(dir, 'ws', 'AGENTS.md'), 'my own notes');
    const again = realManager(dir, { port: await freePort(), facts: { hostname: 'h', os: 'win32', os_version: 'X', user: 'u', shell: 's', path_sep: '/', package_manager: 'p', modifier_key: 'k', workspace_dir: '/w' } });
    await again.manager.start();
    assert.equal(fs.readFileSync(path.join(dir, 'ws', 'AGENTS.md'), 'utf8'), 'my own notes');
    await again.manager.stop();
  } finally { delete process.env.JARVIS_TEST_SECRET_TOKEN; await manager.stop(); rmDir(dir); }
});

