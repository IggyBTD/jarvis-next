function realManager(dir, over = {}) {
  const log = path.join(dir, 'oc.log');
  return { log, manager: createOpencodeManager({ workspaceDir: path.join(dir, 'ws'), serverUrl: 'http://pc:7410', modelToken: 'x'.repeat(64), version: '1.19.1', command: process.execPath, argsPrefix: [BIN], extraEnv: { FAKE_OPENCODE_LOG: log }, backoff: { min: 30, max: 60, stable: 60000 }, env: process.env, ...over }) };
}
const lines = (f) => fs.readFileSync(f, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));

test('routes: discovered from /doc for both versions; only once or reject can ever be sent', () => {
  const fresh = discoverRoutes({ info: { version: '1.19.1' }, paths: { '/permission': {}, '/permission/{requestID}/reply': {}, '/session/{sessionID}/prompt_async': {}, '/session/{sessionID}/abort': {}, '/session/{sessionID}/shell': {} } });
  assert.deepEqual([fresh.permissionReply, fresh.promptAsync, fresh.shellRoutePresent], ['new', true, true]);
  const old = discoverRoutes({ paths: { '/session/{id}/permissions/{permissionID}': {} } });
  assert.deepEqual([old.permissionReply, old.promptAsync], ['old', false]);
  assert.equal(discoverRoutes({ paths: {} }).permissionReply, null);
  assert.deepEqual(replyRequest(fresh, { id: 'p1' }, 'once'), { method: 'POST', path: '/permission/p1/reply', body: { reply: 'once' } });
  assert.deepEqual(replyRequest(old, { id: 'p1', sessionID: 's1' }, 'reject'), { method: 'POST', path: '/session/s1/permissions/p1', body: { response: 'reject' } });
  for (const bad of ['always', 'ALWAYS', 'allow', '', undefined]) assert.throws(() => replyRequest(fresh, { id: 'p1' }, bad), /only once or reject/);
  assert.throws(() => replyRequest(discoverRoutes({ paths: {} }), { id: 'p' }, 'once'), /does not advertise/);
  assert.deepEqual(parsePermission({ id: 'a', sessionID: 's', permission: 'bash', patterns: ['ls'], metadata: { command: 'ls -la' } }).command, 'ls -la');
  assert.equal(parsePermission({ id: 'a', type: 'edit', pattern: 'src/x.js' }).patterns[0], 'src/x.js');
});

